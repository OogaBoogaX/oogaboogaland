// Writes the Ember Den's lounge playlist into src/js/lounge-track-<key>.js, one deferred group a track, on the
// HALLOWEEN hunt's pattern (src/js/ghost-track-*.js): the encoded file's bytes as one base64 string on
// `BL.loungeMusic[<key>]`, decoded by the player with `decodeAudioData`.
//
// Run from the repository:  node scripts/lounge-tracks.mjs <musicDir>
// musicDir (outside the repository; the recordings are not kept in it) must hold the four .m4a files made from the
// downloads with macOS's afconvert:
//   afconvert -f m4af -d aac -b 96000 -q 127 "Lobby Time.mp3" lobby-time.m4a   (and so on for each track)
// The script only reads those files and writes the four modules; it runs nothing from the music folder.
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, "..");
if (!process.argv[2]) throw new Error("usage: node scripts/lounge-tracks.mjs <musicDir>");
const music = resolve(process.argv[2]);

// key: the group's suffix and the BL.loungeMusic key; file: the encoded file in musicDir; source: the download.
const TRACKS = [
  { key: "lobby", file: "lobby-time.m4a", title: "Lobby Time", from: "256 kbps MP3", year: 2016, isrc: "USUAN1600054" },
  { key: "cool", file: "cool-vibes.m4a", title: "Cool Vibes", from: "320 kbps MP3", year: 2011, isrc: null },
  { key: "venus", file: "vibing-over-venus.m4a", title: "Vibing Over Venus", from: "160 kbps MP3", year: 2023, isrc: "USUAN2300005" },
  { key: "bossa", file: "bossa-antigua.m4a", title: "Bossa Antigua", from: "256 kbps MP3", year: 2017, isrc: "USUAN1700069" }
];

const mb = (n) => `${(n / 1e6).toFixed(2)} MB`;
for (const t of TRACKS) {
  const input = join(music, t.file);
  if (!existsSync(input)) throw new Error(`missing ${input}`);
  const bytes = readFileSync(input);
  // An MP4/M4A file opens with an `ftyp` box; refuse anything else so a wrong file is never embedded.
  if (bytes.toString("latin1", 4, 8) !== "ftyp") throw new Error(`${t.file} is not an MP4/M4A file`);
  const base64 = bytes.toString("base64");
  const group = `lounge-track-${t.key}`;
  const text = `/*
 * "${t.title}" Kevin MacLeod (incompetech.com)
 * Licensed under Creative Commons: By Attribution 4.0
 * https://creativecommons.org/licenses/by/4.0/
 *
 * Source: Kevin MacLeod's library at incompetech.com (${t.year}${t.isrc ? `, ISRC ${t.isrc}` : ""}), downloaded as a ${t.from}.
 * Changes: re-encoded to AAC (M4A) at 96 kbps stereo; nothing cut or mixed. Not covered by the repository's
 * Ooga Booga License: this recording stays under CC BY 4.0 (see CREDITS.md).
 */
// The Ember Den's lounge playlist, one track. A deferred group of its own (data-defer="${group}"), fetched only when
// poker-audio.js is about to play it. Generated by scripts/lounge-tracks.mjs.
(() => {
  "use strict";
  const BL = window.BL = window.BL || {};
  (BL.loungeMusic = BL.loungeMusic || {}).${t.key} = "${base64}";
})();
`;
  if (/<\/script|<!--/i.test(text)) throw new Error(`${t.file}: text would break the inline block`);
  if (/[^\x00-\x7f]/.test(text)) throw new Error(`${t.file}: non-ASCII text`);
  const out = join(root, "src", "js", `${group}.js`);
  writeFileSync(out, text);
  console.log(`${group}.js  m4a ${mb(bytes.length)}  module ${mb(text.length)}`);
}
