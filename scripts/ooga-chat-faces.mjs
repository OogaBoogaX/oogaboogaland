// Draws every Ooga's face for Ooga Chat's Contributing Oogas (#656), with the island's own renderer as the island's
// stats strip draws one (hud.js `renderFaceIcon` at 80 pixels, the caveman built from each character's traits), into one
// sheet: `npm run ooga-chat:faces` writes src/ooga-chat/art/ooga-faces.png and src/ooga-chat/ooga-chat-faces.js (where
// each Ooga's face stands on the sheet by handle, and the default Ooga's face for anyone added since). The app cannot
// load the 3D engine, so its faces are this sheet's: run it again when an Ooga is added or changes its look, and
// commit both files. It opens the source page in the suite's Chrome, so `npm run build` first. Needs Chrome.
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { dispose, launch } from "../test/browser.mjs";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const SIZE = 80, COLUMNS = 8;
// The face a contributor added since the last run shows: the hashed default Ooga's, under a name no handle can have.
const FALLBACK = "ooga chat";

const draw = `(size, columns, fallback) => {
  const BL = window.BL, names = BL.characters.all().map((c) => c.handle).concat(fallback);
  const rows = Math.ceil(names.length / columns), sheet = document.createElement("canvas");
  sheet.width = columns * size; sheet.height = rows * size;
  const g = sheet.getContext("2d"), cells = {};
  names.forEach((name, i) => {
    const canvas = document.createElement("canvas");
    BL.hud.renderFaceIcon(canvas, BL.models.caveman(BL.contributors.traitsFor(name)), null, size);
    g.drawImage(canvas, (i % columns) * size, Math.floor(i / columns) * size, size, size);
    cells[name.toLowerCase()] = i;
  });
  return { png: sheet.toDataURL("image/png"), cells, fallback: cells[fallback] };
}`;

const b = await launch({ w: 800, h: 600 });
try {
  await b.open(`file://${join(root, "src", "index.html")}?debug=1&nosim=1&net=0&pos=0&welcome=0&hour=12&day=80&scene=lab`);
  const t0 = Date.now();
  while (!(await b.evaluate("!!(window.__ooga && window.__ooga.scene)").catch(() => false))) {
    if (Date.now() - t0 > 60000) throw new Error("The page did not start. Run npm run build first.");
    await b.sleep(100);
  }
  const { png, cells, fallback } = await b.evaluate(`(${draw})(${SIZE}, ${COLUMNS}, ${JSON.stringify(FALLBACK)})`);
  delete cells[FALLBACK];
  writeFileSync(join(root, "src", "ooga-chat", "art", "ooga-faces.png"), Buffer.from(png.split(",")[1], "base64"));
  const sorted = Object.fromEntries(Object.entries(cells).sort(([a], [b]) => a < b ? -1 : 1));
  writeFileSync(join(root, "src", "ooga-chat", "ooga-chat-faces.js"), `// Generated by scripts/ooga-chat-faces.mjs, never edited: where each Ooga's face stands on art/ooga-faces.png (#656),
// a square of \`size\` pixels in \`columns\` columns, by handle in lower case, and the default Ooga's face (\`fallback\`) for
// anyone added since the sheet was drawn.
(() => {
  "use strict";
  const BL = window.BL = window.BL || {};
  BL.oogaChatFaces = Object.freeze({ size: ${SIZE}, columns: ${COLUMNS}, fallback: ${fallback}, cells: Object.freeze(${JSON.stringify(sorted)}) });
})();
`);
  console.log(`src/ooga-chat/art/ooga-faces.png: ${Object.keys(sorted).length} faces and the default`);
} finally {
  b.close();
  await dispose();
}
