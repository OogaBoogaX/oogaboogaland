// Regenerates src/js/emoji-data.js, the reaction picker's emoji (reactions.js) and the set the room accepts
// (reaction-policy.js): node scripts/emoji-data.mjs [path-or-url to emoji-test.txt]. By default it pulls Unicode's
// emoji-test.txt for EMOJI and keeps every fully-qualified emoji up to MAX_VERSION, in CLDR order under its group,
// with its name, so devices a few years old still draw every one. An emoji with skin tones keeps its light-skin form,
// whose U+1F3FB the page swaps for the visitor's tone; the script checks every other tone of it is listed too. On any
// failure it warns and keeps the committed file. Run by hand when the Unicode version moves.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const EMOJI = "15.1", MAX_VERSION = 15.0;
const LIGHT = "\u{1F3FB}", TONES = ["\u{1F3FC}", "\u{1F3FD}", "\u{1F3FE}", "\u{1F3FF}"];
const TONE_NAMES = ["medium-light", "medium", "medium-dark", "dark"];
const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const target = join(root, "src", "js", "emoji-data.js");
const source = process.argv[2] || `https://unicode.org/Public/emoji/${EMOJI}/emoji-test.txt`;

try {
  const text = /^https?:/.test(source) ? await (await fetch(source)).text() : readFileSync(source, "utf8");
  const line = /^([0-9A-F ]+?)\s*;\s*([a-z-]+)\s*#\s*(\S+)\s+E(\d+\.\d+)\s+(.+)$/;
  const groups = [], byName = new Map(), qualified = new Set();
  let group = null;
  for (const raw of text.split("\n")) {
    const head = raw.match(/^# group: (.+)$/);
    if (head) {
      group = head[1] === "Component" ? null : { name: head[1], emoji: [] };
      if (group) groups.push(group);
      continue;
    }
    const m = raw.match(line);
    if (!m || m[2] !== "fully-qualified") continue;
    const emoji = String.fromCodePoint(...m[1].split(" ").map((h) => parseInt(h, 16)));
    if (emoji !== m[3]) throw new Error(`code points and emoji disagree: ${raw}`);
    qualified.add(emoji);
    byName.set(m[5], emoji);
    if (!group || Number(m[4]) > MAX_VERSION || /[\u{1F3FB}-\u{1F3FF}]/u.test(emoji)) continue;
    group.emoji.push([emoji, m[5]]);
  }
  let toned = 0;
  for (const g of groups) {
    for (const entry of g.emoji) {
      const light = byName.get(`${entry[1]}: light skin tone`);
      if (!light) continue;
      for (let i = 0; i < TONES.length; i++) {
        const other = light.replaceAll(LIGHT, TONES[i]);
        if (!qualified.has(other) || byName.get(`${entry[1]}: ${TONE_NAMES[i]} skin tone`) !== other) throw new Error(`${entry[1]}: no ${TONE_NAMES[i]} form by its light one`);
      }
      entry.push(light);
      toned++;
    }
  }
  const count = groups.reduce((n, g) => n + g.emoji.length, 0);
  if (groups.length !== 9 || count < 1500) throw new Error(`unexpected shape: ${groups.length} groups, ${count} emoji`);
  const body = groups.map((g) => `    { name: ${JSON.stringify(g.name)}, emoji: [\n${g.emoji.map((e) => `      ${JSON.stringify(e)}`).join(",\n")}\n    ] }`).join(",\n");
  writeFileSync(target, `// Generated by scripts/emoji-data.mjs from Unicode's emoji-test.txt (Emoji ${EMOJI}), every fully-qualified emoji up to
// Emoji ${MAX_VERSION.toFixed(1)} in CLDR order: [emoji, name] or, where it takes a skin tone, [emoji, name, its light-skin form]. Shared
// unchanged by the page and the Worker (reaction-policy.js). Do not edit by hand.
(() => {
  "use strict";
  const scope = typeof window === "undefined" ? globalThis : window;
  const BL = scope.BL = scope.BL || {};
  BL.emojiData = Object.freeze({ version: ${JSON.stringify(EMOJI)}, max: ${MAX_VERSION}, groups: [
${body}
  ] });
})();
`);
  console.log(`wrote ${target}: ${count} emoji in ${groups.length} groups, ${toned} with skin tones`);
} catch (e) {
  console.warn(`keeping the committed emoji data: ${e.message}`);
}
