// Regenerates src/js/island-layout.js, the island's routine tables the server's island world runs on (island-sim.js):
// node scripts/island-layout.mjs, after `npm run build`. The tables come from the real hub, built in the suite's Chrome
// from the built page (`routineLayout` in scene-hub.js), because its fire seats, stroll spots and work places depend
// on the props it scatters and on the island's own geometry, which only the page builds. Run it again whenever the
// meadow, its paths, the caves or the cast change; the hub's "island layout" check says when it is due.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { dispose, launch } from "../test/browser.mjs";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const target = join(root, "src", "js", "island-layout.js");
const page = `file://${join(root, "oogaboogaland.html")}?debug=1&nosim=1&net=0&pos=0&welcome=0&hour=12&day=80&rain=0`;
const b = await launch({ w: 800, h: 600 });
let layout;
try {
  await b.open(page);
  const t0 = Date.now();
  while (!(await b.evaluate(`!!window.__ooga && __ooga.renderedFrames >= 2 && __ooga.scene === "hub"`).catch(() => false))) {
    if (Date.now() - t0 > 60000) throw new Error("the hub did not draw");
    await b.sleep(100);
  }
  layout = JSON.parse(await b.evaluate(`JSON.stringify(BL.scenes.hub.debug.routineLayout())`));
} finally {
  b.close();
  await dispose();
}
const text = `// Generated by scripts/island-layout.mjs from the built hub; do not edit. The island's routine tables for its world
// (island-sim.js), shared unchanged by the page and the Worker.
(() => {
  "use strict";
  const scope = typeof window === "undefined" ? globalThis : window;
  const BL = scope.BL = scope.BL || {};
  BL.islandLayout = ${JSON.stringify(layout)};
})();
`;
let before = "";
try { before = readFileSync(target, "utf8"); } catch { /* first run */ }
if (before === text) console.log("src/js/island-layout.js is current");
else {
  writeFileSync(target, text);
  console.log(`src/js/island-layout.js: ${layout.seats.length} seats, ${layout.spots.length} spots, ${layout.sites.length} sites`);
}
